// node tools/sync-colours.mjs [--write]
// Keep the runtime HEX catalogue reproducible after research CSVs are removed.
import { readFileSync, writeFileSync } from "node:fs";
const source = JSON.parse(readFileSync(new URL("./data/channel-colours-v52.json", import.meta.url), "utf8"));
if (process.argv.slice(2).some((arg) => arg !== "--write")) throw Error("Usage: node tools/sync-colours.mjs [--write]");
const seen = new Set();
if (!/^[0-9a-f]{64}$/.test(source.sha256) || !Array.isArray(source.colours) || !source.colours.length) throw Error("Invalid source catalogue");
for (const row of source.colours) {
  if (typeof row.channel !== "string" || typeof row.hex !== "string" || !/^UC[A-Za-z0-9_-]{22}$/.test(row.channel) || !/^#[0-9A-F]{6}$/.test(row.hex) || seen.has(row.channel)) throw Error("Invalid or duplicate colour row");
  seen.add(row.channel);
}
const file = new URL("../src/store.js", import.meta.url);
const text = readFileSync(file, "utf8");
const start = "  // BEGIN V52 HEX COLOURS\n", end = "  // END V52 HEX COLOURS\n";
if (text.split(start).length !== 2 || text.split(end).length !== 2) throw Error("Missing or duplicate catalogue markers");
const block = start + "  // The selected HEX is authoritative, including lightness and chroma.\n" +
  "  // Generated by tools/sync-colours.mjs from tools/data/channel-colours-v52.json.\n" +
  "  const OSHI_COLORS = Object.assign(Object.create(null), {\n" +
  [...source.colours].sort((a, b) => a.channel < b.channel ? -1 : a.channel > b.channel ? 1 : 0)
    .map((row) => `    ${JSON.stringify(row.channel)}: ${JSON.stringify(row.hex)},\n`).join("") + "  });\n" + end;
const at = text.indexOf(start), until = text.indexOf(end) + end.length;
if (until <= at) throw Error("Invalid catalogue marker order");
const next = text.slice(0, at) + block + text.slice(until);
if (process.argv.includes("--write")) writeFileSync(file, next);
else if (next !== text) throw Error("Runtime colours differ from the source; run with --write");
console.log(`ok   ${source.colours.length} complete HEX colours match the v52 source`);
